"""
Maps exposed services/ports to MITRE ATT&CK (Enterprise) techniques and
can export an ATT&CK Navigator layer JSON file for a visual heatmap.

This uses a small, hand-curated lookup table rather than the full live
ATT&CK STIX dataset (e.g. via the `mitreattack-python` library) -- that
keeps the tool dependency-light and usable offline, at the cost of being
a simplification. Treat the mapping as illustrative/educational, not an
authoritative threat model: cross-check anything you cite against
https://attack.mitre.org before using it in a real assessment.
"""

import json
from collections import defaultdict

# service/port keyword (lowercased) -> list of (technique_id, technique_name)
SERVICE_TECHNIQUES = {
    "ssh": [("T1021.004", "Remote Services: SSH")],
    "telnet": [
        ("T1110", "Brute Force"),
        ("T1040", "Network Sniffing"),
    ],
    "ftp": [
        ("T1071.002", "Application Layer Protocol: File Transfer Protocols"),
    ],
    "http": [
        ("T1190", "Exploit Public-Facing Application"),
        ("T1071.001", "Application Layer Protocol: Web Protocols"),
    ],
    "https": [
        ("T1190", "Exploit Public-Facing Application"),
        ("T1071.001", "Application Layer Protocol: Web Protocols"),
    ],
    "microsoft-ds": [  # SMB, port 445
        ("T1021.002", "Remote Services: SMB/Windows Admin Shares"),
        ("T1135", "Network Share Discovery"),
    ],
    "netbios-ssn": [
        ("T1046", "Network Service Discovery"),
        ("T1135", "Network Share Discovery"),
    ],
    "ms-wbt-server": [  # RDP, port 3389
        ("T1021.001", "Remote Services: Remote Desktop Protocol"),
    ],
    "ms-sql-s": [("T1210", "Exploitation of Remote Services")],
    "mysql": [("T1210", "Exploitation of Remote Services")],
    "postgresql": [("T1210", "Exploitation of Remote Services")],
    "snmp": [("T1046", "Network Service Discovery")],
    "vnc": [("T1021.005", "Remote Services: VNC")],
    "rpcbind": [("T1046", "Network Service Discovery")],
    "domain": [("T1071.004", "Application Layer Protocol: DNS")],  # DNS, port 53
}

# Applied to every open service, since an open/reachable port is by
# definition discoverable over the network.
BASELINE_TECHNIQUE = ("T1046", "Network Service Discovery")


def techniques_for_service(service_name, port=None):
    name = (service_name or "").strip().lower()
    techniques = set(SERVICE_TECHNIQUES.get(name, []))
    techniques.add(BASELINE_TECHNIQUE)
    return techniques


def map_host_techniques(host_services):
    """
    host_services: {port: {"name": ..., ...}}
    Returns a set of (technique_id, technique_name) tuples for the host.
    """
    techniques = set()
    for port, info in host_services.items():
        techniques |= techniques_for_service(info.get("name"), port)
    return techniques


def map_all_hosts(scan_hosts):
    """
    scan_hosts: {host_ip: {"services": {port: {...}}, ...}}
    Returns {host_ip: [{"id":..., "name":...}, ...]}
    """
    result = {}
    for host, data in scan_hosts.items():
        techniques = map_host_techniques(data.get("services", {}))
        result[host] = sorted(
            [{"id": tid, "name": tname} for tid, tname in techniques],
            key=lambda t: t["id"],
        )
    return result


def export_navigator_layer(scan_hosts, output_path, layer_name="NetMap Scan"):
    """
    Writes an ATT&CK Navigator layer JSON (schema v4.5). Import it at
    https://mitre-attack.github.io/attack-navigator/ to get a heatmap of
    which techniques your scanned network exposes, and how many hosts
    each one shows up on.
    """
    technique_host_counts = defaultdict(int)
    technique_names = {}
    technique_hosts = defaultdict(list)

    for host, data in scan_hosts.items():
        for tid, tname in map_host_techniques(data.get("services", {})):
            technique_host_counts[tid] += 1
            technique_names[tid] = tname
            technique_hosts[tid].append(host)

    max_count = max(technique_host_counts.values(), default=1)

    layer = {
        "name": layer_name,
        "versions": {"attack": "15", "navigator": "5.1", "layer": "4.5"},
        "domain": "enterprise-attack",
        "description": "Auto-generated by NetMap from a network scan. "
                        "Technique mapping is a curated approximation -- see mitre_mapping.py.",
        "sorting": 3,  # sort by score descending
        "layout": {"layout": "side", "showAggregateScores": True},
        "gradient": {
            "colors": ["#ffffff", "#ffcc00", "#c0392b"],
            "minValue": 0,
            "maxValue": max_count,
        },
        "techniques": [
            {
                "techniqueID": tid,
                "score": count,
                "comment": f"Seen on {count} host(s): {', '.join(technique_hosts[tid])}",
            }
            for tid, count in sorted(technique_host_counts.items())
        ],
    }

    with open(output_path, "w") as f:
        json.dump(layer, f, indent=2)

    return output_path
